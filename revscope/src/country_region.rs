/// Returns major cities for synthetic data generation, keyed by ISO country code.
pub fn major_cities_for_country(country: &str) -> Option<&'static [&'static str]> {
    MAJOR_CITIES.get(country).copied()
}

/// Resolve a display name for an ISO 3166-1 alpha-2 country code.
pub(crate) fn country_name_for_country(country: Option<&str>) -> String {
    match country {
        Some(code) => COUNTRY_NAMES.get(code).copied().unwrap_or(code).to_string(),
        None => "Unknown".to_string(),
    }
}

/// True when `code` is an uppercase ISO 3166-1 alpha-2 key in [`COUNTRY_NAMES`].
///
/// The Cloudflare country fallback is the only non-test caller, and that path
/// is compiled out when the GeoIP database is embedded.
#[cfg_attr(geoip_embedded, allow(dead_code))]
pub(crate) fn is_known_country_code(code: &str) -> bool {
    COUNTRY_NAMES.contains_key(code)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_country_code_to_display_name() {
        assert_eq!(country_name_for_country(Some("US")), "United States");
        assert_eq!(country_name_for_country(Some("GB")), "United Kingdom");
        assert_eq!(country_name_for_country(None), "Unknown");
        assert_eq!(country_name_for_country(Some("ZZ")), "ZZ");
        assert!(is_known_country_code("US"));
        assert!(!is_known_country_code("ZZ"));
        assert!(!is_known_country_code("xx"));
    }

    #[test]
    fn major_cities_cover_generate_countries_with_four_to_fifteen_entries() {
        const GENERATE_COUNTRIES: &[&str] = &[
            "US", "CA", "MX", "AR", "CL", "BR", "GB", "IE", "DE", "FR", "NL", "IT", "ES", "SE",
            "NO", "CH", "AT", "BE", "PL", "PT", "DK", "FI", "TR", "AE", "SA", "IL", "QA", "EG",
            "JP", "IN", "CN", "HK", "TW", "SG", "KR", "ID", "PH", "NZ", "AU", "ZA", "NG", "KE",
        ];
        for country in GENERATE_COUNTRIES {
            let cities = major_cities_for_country(country)
                .unwrap_or_else(|| panic!("missing major cities for generate country {country}"));
            assert!(
                (4..=15).contains(&cities.len()),
                "{country} has {} cities, expected 4-15",
                cities.len()
            );
        }
    }
}
